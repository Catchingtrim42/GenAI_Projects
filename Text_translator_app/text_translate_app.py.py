import gradio as gr
from transformers import AutoTokenizer, AutoModelForSeq2SeqLM

# 1. Load Meta's NLLB-200 distilled 600M model and tokenizer
MODEL_NAME = "facebook/nllb-200-distilled-600M"
print("Loading NLLB-200 tokenizer and model...")

tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
model = AutoModelForSeq2SeqLM.from_pretrained(MODEL_NAME)

# Language code tokens for NLLB-200
# eng_Latn = English in Latin script
# tam_Taml = Tamil in Tamil script
SRC_LANG = "eng_Latn"
TGT_LANG = "tam_Taml"

def translate_english_to_tamil(text):
    if not text or not text.strip():
        return ""

    # Tokenize input text
    inputs = tokenizer(text, return_tensors="pt")

    # Set target language to Tamil
    forced_bos_token_id = tokenizer.convert_tokens_to_ids(TGT_LANG)

    # Generate Tamil translation
    outputs = model.generate(
        **inputs,
        forced_bos_token_id=forced_bos_token_id,
        max_new_tokens=256
    )

    # Decode token IDs back to text
    translated_text = tokenizer.decode(outputs[0], skip_special_tokens=True)
    return translated_text

# 2. Build Gradio Interface
demo = gr.Interface(
    fn=translate_english_to_tamil,
    inputs=gr.Textbox(
        lines=5,
        placeholder="Type English sentence here...",
        label="English Input"
    ),
    outputs=gr.Textbox(
        lines=5,
        label="Tamil Translation (தமிழ்)"
    ),
    title="English to Tamil Translator",
    description="Welcome to our Neural Machine Translation powered by Meta NLLB-200 distilled model.",
    examples=[
        ["Hello, how are you today?"],
        ["Welcome to our language translation web application."],
        ["Thank you very much for your assistance."]
    ]
)

if __name__ == "__main__":
    demo.launch()