import gradio as gr
import torch
import matplotlib.pyplot as plt
import matplotlib.patches as patches
import io
from PIL import Image

def detect_objects(image, threshold):
    if image is None:
        return None

    # Process image
    inputs = image_processor(images=image, return_tensors="pt")
    with torch.no_grad():
        outputs = model(**inputs)

    # Post-process predictions
    target_sizes = torch.tensor([image.size[::-1]])
    results = image_processor.post_process_object_detection(
        outputs,
        threshold=threshold,
        target_sizes=target_sizes
    )[0]

    # Plot
    fig, ax = plt.subplots(1, figsize=(10, 8))
    ax.imshow(image)

    scores = results["scores"]
    labels = results["labels"]
    boxes = results["boxes"]

    if len(scores) > 0:
        colors = plt.cm.hsv(torch.linspace(0, 1, len(scores)))
        for score, label, box, color in zip(scores, labels, boxes, colors):
            xmin, ymin, xmax, ymax = box.tolist()
            width, height = xmax - xmin, ymax - ymin

            # Draw rectangle
            rect = patches.Rectangle((xmin, ymin), width, height, linewidth=2, edgecolor=color, facecolor='none')
            ax.add_patch(rect)

            # Add label text
            class_name = model.config.id2label[label.item()]
            ax.text(
                xmin, ymin - 5,
                f"{class_name}: {score:.2f}",
                color='white', fontsize=10,
                bbox=dict(facecolor=color, alpha=0.8, pad=2, edgecolor='none')
            )

    plt.axis('off')
    plt.tight_layout()

    # Save plot to buffer
    buf = io.BytesIO()
    plt.savefig(buf, format='png', bbox_inches='tight', pad_inches=0)
    buf.seek(0)
    output_image = Image.open(buf)
    plt.close(fig)

    return output_image

# Create Gradio interface
demo = gr.Interface(
    fn=detect_objects,
    inputs=[
        gr.Image(type="pil", label="Upload Image"),
        gr.Slider(minimum=0.1, maximum=1.0, value=0.9, step=0.05, label="Confidence Threshold")
    ],
    outputs=gr.Image(type="pil", label="Detection Result"),
    title="YOLO Object Detection App",
    description="Upload an image and adjust the confidence threshold to find and label objects using the YOLOs model.",
    examples=[[image, 0.9]]
)

# Launch the app with a public link
demo.launch(share=True)