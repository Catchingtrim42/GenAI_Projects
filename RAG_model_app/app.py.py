# Global variables for RAG state
vector_store = None
embeddings = HuggingFaceEmbeddings(model_name="all-MiniLM-L6-v2")


def process_document(file_obj):
    """Processes uploaded PDF document and creates a vector store index."""
    global vector_store
    if file_obj is None:
        return "Please upload a valid PDF document."

    try:
        loader = PyPDFLoader(file_obj.name)
        documents = loader.load()

        text_splitter = RecursiveCharacterTextSplitter(
            chunk_size=500, chunk_overlap=50
        )
        docs = text_splitter.split_documents(documents)

        vector_store = FAISS.from_documents(docs, embeddings)

        return f"Successfully indexed {os.path.basename(file_obj.name)} ({len(docs)} chunks created)."
    except Exception as e:
        return f"Error processing document: {str(e)}"


def answer_question(message, history, top_k):
    """Retrieves context and appends response to conversation history."""
    global vector_store

    if vector_store is None:
        history = history + [
            (
                message,
                "Please upload and index a document first before asking questions.",
            )
        ]
        return history, ""

    retriever = vector_store.as_retriever(search_kwargs={"k": int(top_k)})
    docs = retriever.invoke(message)

    if not docs:
        response = "No relevant context found in the uploaded document."
    else:
        context_str = "\n\n".join(
            [f"**Excerpt {i+1}:** {d.page_content}" for i, d in enumerate(docs)]
        )
        response = f"**Retrieved Answer Context:**\n\n{context_str}"

    history = history + [(message, response)]
    return history, ""


